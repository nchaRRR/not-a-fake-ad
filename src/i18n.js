function detect() {
  try {
    const saved = localStorage.getItem('not-a-fake-ad-lang');
    if (saved === 'en' || saved === 'tr') return saved;
  } catch (e) { /* storage unavailable */ }
  const nav = (navigator.languages && navigator.languages[0]) || navigator.language || 'en';
  return nav.toLowerCase().startsWith('tr') ? 'tr' : 'en';
}

let lang = detect();

export const getLang = () => lang;

export function setLang(next) {
  lang = next === 'tr' ? 'tr' : 'en';
  try { localStorage.setItem('not-a-fake-ad-lang', lang); } catch (e) { /* ignore */ }
  document.documentElement.lang = lang;
  applyStatic();
}

export function t(key, vars) {
  const v = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (typeof v !== 'string' || !vars) return v;
  return v.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

// Fills every element marked data-i18n (text) or data-i18n-label (aria-label).
export function applyStatic() {
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-label]')) el.setAttribute('aria-label', t(el.dataset.i18nLabel));
}

document.documentElement.lang = lang;
